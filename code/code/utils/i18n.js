// 模板填充：format('你好，{name}', { name: '小明' }) -> '你好，小明'
function format(tpl, map) {
  return tpl.replace(/\{(\w+)\}/g, (m, k) => (map && map[k] !== undefined ? String(map[k]) : m))
}

